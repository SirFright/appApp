function build(seed: Seed): Contractor {
  const key = seed.town.toLowerCase()
  const center = CT_TOWNS[key] ?? CT_CENTER
  return {
    id: seed.cred,
    businessName: seed.business,
    licenseHolder: seed.holder,
    licenseType: 'E-1',
    licenseTypeLabel: 'E-1 · Unlimited Electrical Contractor',
    credentialNumber: seed.cred,
    status: 'Active',
    issueDate: seed.issue,
    expirationDate: EXPIRES,
    address: seed.addr,
    town: seed.town,
    state: 'CT',
    zip: seed.zip,
    lat: +(center[0] + seed.off[0]).toFixed(5),
    lng: +(center[1] + seed.off[1]).toFixed(5),
    approxLocation: false,
    phone: seed.phone,
    website: `https://${seed.site}`,
    email: `info@${seed.site}`,
    description: seed.desc,
    source: 'sample',
  }
}

export const SAMPLE_CONTRACTORS: Contractor[] = SEEDS.map(build)
